import assert from 'node:assert/strict';
import {createTrainingApi, DEFAULT_CONFIG, isActive} from '../lib/training/api.ts';

const calls = [];
const fetcher = async (url, options) => {
  calls.push({url,options});
  return new Response(JSON.stringify({id:'task',status:'running'}), {status:201});
};
const api = createTrainingApi('http://localhost:8000/', fetcher);
await api.create(DEFAULT_CONFIG, 'real corpus');
assert.equal(calls[0].url,'http://localhost:8000/tasks');
assert.equal(calls[0].options.method,'POST');
assert.deepEqual(JSON.parse(calls[0].options.body),{config:DEFAULT_CONFIG,text:'real corpus'});
await api.stop('task');
assert.equal(calls[1].url,'http://localhost:8000/tasks/task/stop');
await api.resume('task',400);
assert.deepEqual(JSON.parse(calls[2].options.body),{max_steps:400});
await api.generate('task',{prompt:'First',max_new_tokens:8,temperature:.8,top_k:20,seed:42,layer:0,head:0});
assert.equal(calls[3].url,'http://localhost:8000/tasks/task/generate');
await api.load('checkpoint','cuda');
assert.equal(calls[4].url,'http://localhost:8000/checkpoints/checkpoint/load');
assert.deepEqual(JSON.parse(calls[4].options.body),{device:'cuda'});
const predictionOptions = {prompt:'First Citizen:',temperature:.8,top_k:20,seed:42,layer:0,head:0};
await api.predict('task',predictionOptions);
assert.equal(calls[5].url,'http://localhost:8000/tasks/task/predict');
await api.step('task',{...predictionOptions,context_tokens:['First','Citizen',':']});
assert.equal(calls[6].url,'http://localhost:8000/tasks/task/step');
assert.deepEqual(JSON.parse(calls[6].options.body).context_tokens,['First','Citizen',':']);
assert.equal(api.download('a'.repeat(32)),`http://localhost:8000/checkpoints/${'a'.repeat(32)}/download`);
assert.throws(()=>createTrainingApi('file:///secret'),/HTTP/);
assert.throws(()=>createTrainingApi('http://user:password@localhost'),/HTTP/);
const invalid = createTrainingApi('http://localhost:8000',async()=>new Response(JSON.stringify({detail:'budget exceeded'}),{status:422}));
await assert.rejects(invalid.create(DEFAULT_CONFIG),/budget exceeded/);
const validation = createTrainingApi('http://localhost:8000',async()=>new Response(JSON.stringify({detail:[{msg:'heads mismatch'}]}),{status:422}));
await assert.rejects(validation.create(DEFAULT_CONFIG),/heads mismatch/);
const crashed = createTrainingApi('http://localhost:8000',async()=>new Response('Internal Server Error',{status:500}));
await assert.rejects(crashed.health(),/无效响应.*500/);
const offline = createTrainingApi('http://localhost:8000',async()=>{throw new TypeError('Failed to fetch');});
await assert.rejects(offline.health(),/无法连接训练服务/);
assert.equal(isActive({status:'stopping'}),true);
assert.equal(isActive({status:'loaded'}),false);
assert.equal(isActive(null),false);
console.log('Training API contracts, error handling and lifecycle checks passed.');
